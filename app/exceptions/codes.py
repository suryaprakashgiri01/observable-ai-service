"""Stable, machine-readable error codes and the HTTP status each maps to."""

from __future__ import annotations

from enum import StrEnum


class ErrorCode(StrEnum):
    VALIDATION_ERROR = "VALIDATION_ERROR"
    AUTH_REQUIRED = "AUTH_REQUIRED"
    AUTH_INVALID = "AUTH_INVALID"
    FORBIDDEN = "FORBIDDEN"
    MODEL_NOT_FOUND = "MODEL_NOT_FOUND"
    MODEL_UNAVAILABLE = "MODEL_UNAVAILABLE"
    MODEL_CONFLICT = "MODEL_CONFLICT"
    MODEL_LIMIT_REACHED = "MODEL_LIMIT_REACHED"
    ENCRYPTION_NOT_CONFIGURED = "ENCRYPTION_NOT_CONFIGURED"
    TICKET_NOT_FOUND = "TICKET_NOT_FOUND"
    NOT_FOUND = "NOT_FOUND"
    TOOL_FAILED = "TOOL_FAILED"
    LLM_UNAVAILABLE = "LLM_UNAVAILABLE"
    INTERNAL_ERROR = "INTERNAL_ERROR"


STATUS_BY_CODE: dict[ErrorCode, int] = {
    ErrorCode.VALIDATION_ERROR: 422,
    ErrorCode.AUTH_REQUIRED: 401,
    ErrorCode.AUTH_INVALID: 401,
    ErrorCode.FORBIDDEN: 403,
    ErrorCode.MODEL_NOT_FOUND: 400,
    ErrorCode.MODEL_UNAVAILABLE: 400,
    ErrorCode.MODEL_CONFLICT: 409,
    ErrorCode.MODEL_LIMIT_REACHED: 409,
    ErrorCode.ENCRYPTION_NOT_CONFIGURED: 400,
    ErrorCode.TICKET_NOT_FOUND: 404,
    ErrorCode.NOT_FOUND: 404,
    ErrorCode.TOOL_FAILED: 502,
    ErrorCode.LLM_UNAVAILABLE: 503,
    ErrorCode.INTERNAL_ERROR: 500,
}
